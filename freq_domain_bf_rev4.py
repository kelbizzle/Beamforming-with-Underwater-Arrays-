import numpy as np
import matplotlib.pyplot as plt
import scipy as sci
from scipy.fft import fft, fftfreq, ifft, fftshift, ifftshift
from scipy.io import wavfile

# read in data files
def assemble_data_matrix(num_sensors, path_name):
    '''
    Function Purpose: assemble matrix of hydrophone data where row = hydrophone
    and column = samples from respective sensor

    Inputs: 
            name: datatype, description 
            num_sensors: int, Total # of hydrophones colecting data
            path_name: str, exepects entire pathname including file name up to (not including)
            sensor number, i.e, "/Users/Downloads/Experiment_data/tone1_18/18-Jul-2026 12_03_31ch"
                --> the sensor # and .wav will be appended within the function
    Outputs:
            name: datatype, description
            xdata: np.ndarray, vertically assembled data into a matrix where the shape is # sensors, # of samples per sensor
                i.e xdata.shape(8, 1000)
            fs: float, sampling frequency for data samples (should be the same for all sensors)
    '''
    sensor_data_channels = []
    for sensor in range(num_sensors):
        fs, x = wavfile.read(path_name + str(sensor+1) + ".wav")
        sensor_data_channels.append(x)
    x_data = np.vstack(sensor_data_channels)
    return fs, x_data

# Call function
fs, rcv_matrix = assemble_data_matrix(8,"wav_files/Ch")

#Environmental parameters
temp = 12 #water temp. in celsius
depth = 1/.016 #assuming pressure is negligible for application, setting to reciporical of weight
salinity = 0.0005 #set to .05%, max salinity for freshwater
#approximation for sound velocity in m/s based on environmental parameters
#sound_velocity = 1449.2 + 4.6*temp - (0.055* temp)**2 + (0.00029 * temp)**3 + (1.34- 0.01 * temp) * (salinity-35) + 0.016*depth
sound_velocity = 1500 #simple c assumption

#Sampling parameters
T = 1/fs #sample period

#RCV Arry parameters
el_space = .298
num_els = 8

#null weights generated by NB_CBF_Gernerator.py, technically this is a beam (or set of beams), not yet a null
null_matrix = np.array([[1.-0.j],
[-0.52061427-0.853792j],
[-0.45792156+0.8889926j],
[0.99741527-0.07185248j],
[-0.5806157-0.81417775j],
[-0.39286163+0.9195976j],
[0.98967444-0.14333352j],
[-0.63761565-0.77035465j]])

angle_weights = np.array(np.zeros(num_els), dtype=complex)

#method that builds a num_els row matrix of weights for the chosen angle
def build_weights(angle,freq,num_els,el_spacing,c):
    weights = np.zeros(num_els, dtype=complex)
    for elem in range(num_els):
        tau_d = (elem*el_spacing*np.cos(((angle)*np.pi)/180))/c
        weights[elem] = np.exp(1j*2*np.pi*freq*tau_d)
    return weights

#define azimuth range
min_az = 0
max_az = 180
az_fidelity = 5
az_matrix = np.arange(min_az,max_az + az_fidelity,az_fidelity)
beam_power = []

#mask bins to frequencies we care about and store that frequency data
bins = np.array([fftshift(fftfreq(len(rcv_matrix[0]), T))])
bin_mask = (bins>2380) & (bins<2420)
bins_of_int = bins[bin_mask]
freq_data = np.zeros((num_els,len(bins_of_int)),dtype=complex)
for elem in range(num_els):
    freq_data[elem] = fftshift(fft(rcv_matrix[elem]))[bin_mask.flatten()]

#vars to track highest response
max_power = 0
out_data = np.zeros_like(rcv_matrix[0])
#scan azimuth
for az_i in range(len(az_matrix)):
    #do delay and sum
    time_data = np.zeros_like(rcv_matrix[0]).astype(complex)
    freq_data_shifted = np.zeros_like(freq_data, dtype=complex)
    for i in range(len(bins_of_int)):
        # build weights for look angle
        angle_weights = build_weights(az_matrix[az_i],bins_of_int[i],num_els,el_space,sound_velocity)
        #combine nulls with look vector:
        #identity matrix, num_els x num_els:
        iden = np.eye(num_els)
        #interferer matrix, beams steered towards null angles
        interferers = null_matrix @ np.linalg.pinv(null_matrix)
        #combine matrecies, subtract interferers from identity matrix to make them nulls instead of beams
        comb_matrix = (iden - interferers)@angle_weights
        #comb_matrix = angle_weights
        for num in range(0,7):
            tau_d = (num*el_space*np.cos((az_matrix[az_i]*np.pi)/180))/sound_velocity       
            freq_data_shifted[num,i] = freq_data[num,i] * comb_matrix[num]
    for num in range(0,7):
        time_data += ifft(ifftshift(freq_data_shifted[num]), n=len(time_data))

    #calculate power of delay and sum data
    power = np.var(time_data)
    if power > max_power:
        max_power = power
        out_data = ifft(ifftshift(freq_data_shifted[0]), n=len(time_data)).astype(np.int16)
        #out_data = time_data.astype(np.int16)
    #add to beam array
    beam_power.append(power)

beam_power = np.array(beam_power)
#normalize
beam_power /= np.max(beam_power)

#output wav file
wavfile.write("wav_files/outputData.wav",fs,out_data)

#plot
fig = plt.figure()

plt1 = fig.add_subplot(1,2,1)
plt1.set_xlabel("Scan Angle (degrees)")
plt1.set_ylabel("Power dB//W")
plt1.set_ylim(-50,5)
plt1.set_title("Beamformer Scan: Power vs. Angle")
plt1.grid(True)
plt1.plot(az_matrix,20*np.log10(beam_power))

plt2 = fig.add_subplot(1,2,2,projection='polar')
plt2.set_theta_zero_location("W")
plt2.set_theta_direction(-1)
plt2.set_xlabel("Scan Angle (degrees)")
plt2.set_ylabel("Power dB//W")
plt2.set_ylim(-50,5)
plt2.set_title("Beamformer Scan: Power vs. Angle")
plt2.plot(az_matrix*np.pi/180,20*np.log10(beam_power))

plt.show()